    public static (byte[] Image, WalHeader Header) Load(Stream s)
    {
        using var br=new BinaryReader(s,Encoding.ASCII,true);
        s.Position=0;
        var w=new WalHeader();
        w.Name=PakLoader.ReadFixed(br,32);
        w.Width=br.ReadUInt32();
        w.Height=br.ReadUInt32();
        for(int i=0; i<4; i++)w.Offset[i]=br.ReadInt32();
        w.NextName=PakLoader.ReadFixed(br,32);
        w.Flags=br.ReadUInt32();
        w.Contents=br.ReadUInt32();
        w.Value=br.ReadUInt32();
        s.Position=w.Offset[0];
        int count=checked((int)(w.Width*w.Height));
        var image=new byte[count*3];
        for(int i=0; i<count; i++)
        {
            int idx=s.ReadByte();
            if(idx<0)throw new EndOfStreamException();
            var c=Palette[idx];
            image[i*3]=c[0];
            image[i*3+1]=c[1];
            image[i*3+2]=c[2];
        }
        return (image,w);
    }
